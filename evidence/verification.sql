SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA='PUBLIC'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
SELECT 'USERS' AS ENTITY, COUNT(*) AS ROWS_COUNT FROM USERS
UNION ALL SELECT 'USER_ROLES', COUNT(*) FROM USER_ROLES
UNION ALL SELECT 'RELEASES', COUNT(*) FROM RELEASES
UNION ALL SELECT 'TASKS', COUNT(*) FROM TASKS
UNION ALL SELECT 'USER_ACTIONS', COUNT(*) FROM USER_ACTIONS;
SELECT u.USERNAME, r.ROLE FROM USERS u JOIN USER_ROLES r ON r.USER_ID=u.ID ORDER BY u.ID;
SELECT ID, TITLE, DAYS, DAILY_RATE, RELEASE_ID, OWNER_ID FROM TASKS ORDER BY ID;
SELECT ID, DATE_ACTIONS, ACTOR, ACTION, DESCRIPTION FROM USER_ACTIONS ORDER BY ID DESC FETCH FIRST 20 ROWS ONLY;
